--
-- ★ 幂等：重复执行不报错，且**结果和第一次一致**（不会越跑越多）
--   做法：ID 全部写死成 seed_01…seed_06（不是自增、不随机），
--         再配 ON DUPLICATE KEY UPDATE —— 存在就更新，不存在才插入。
--   ⚠️ 必须**先插 notes 再插 note_tags**：note_tags.note_id 有外键，
--      笔记还不存在时插标签会直接报外键错误。
--
-- 时间一律存 UTC（与前端 localStorage 里既有的 ISO 时间串对齐），
-- "显示成什么时区"由前端负责，库里不做换算。
-- ============================================================


