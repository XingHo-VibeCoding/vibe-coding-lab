/* ------------------------------------------------------------
   假接口：模仿一次"请求数据"的过程
   返回：Promise，结果形如
     { ok: true,  notes: [...] }        取数成功
     { ok: false, message: '错误原因' } 取数失败
   state 传 'loading' 时永远不返回，用来观察"加载中"长什么样
   ------------------------------------------------------------ */
function fetchMockNotes(state) {
  return new Promise((resolve) => {
    // 加载中：故意不 resolve，页面就会一直停在等待状态
    if (state === 'loading') return;

    // 真的取数据要等一下，这里用 700 毫秒模拟
    setTimeout(() => {
      if (state === 'error') {
        resolve({
          ok: false,
          message: '取数据失败：网络开小差了（这是模拟出来的错误，用来检查出错时的页面长什么样）'
        });
        return;
      }
      if (state === 'empty') {
        resolve({ ok: true, notes: [] });
        return;
      }
      resolve({ ok: true, notes: MOCK_NOTES.slice() });
    }, 700);
  });
}
